# insight_ranker.py

from typing import List, Dict

class InsightRanker:
    """
    Handles ranking and prioritization of insights generated by the Kaleidoscope Engine.
    """
    @staticmethod
    def rank_insights(insights: List[Dict]) -> List[Dict]:
        """
        Ranks insights based on their significance and relevance.
        """
        return sorted(insights, key=lambda x: sum(x["weighted_logic"].values()), reverse=True)

    @staticmethod
    def filter_insights(insights: List[Dict], threshold: float) -> List[Dict]:
        """
        Filters insights to include only those above a certain threshold.
        """
        return [insight for insight in insights if sum(insight["weighted_logic"].values()) > threshold]
