# visualization.py

import logging
import matplotlib.pyplot as plt

# Configure logging for Visualization
logging.basicConfig(
    filename="visualization.log",
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s"
)

class Visualization:
    def __init__(self, enable_supernode_tracking=False, data_progression_logging=False):
        """
        Handles the visualization of system metrics, clusters, and supernode progression.

        Args:
            enable_supernode_tracking (bool): Enables tracking and visualization of supernode formation.
            data_progression_logging (bool): Logs detailed progression of data insights.
        """
        self.enable_supernode_tracking = enable_supernode_tracking
        self.data_progression_logging = data_progression_logging

    def visualize_clusters(self, clusters):
        """
        Visualizes node clusters.

        Args:
            clusters (dict): Dictionary containing cluster and node details.

        Returns:
            None
        """
        try:
            print("Cluster Visualization:")
            for cluster_id, nodes in clusters.get("clusters", {}).items():
                print(f"Cluster {cluster_id}:")
                for node in nodes:
                    print(f"  Node {node['id']} - Utilization: {node.get('utilization', 'N/A')}%")

            if self.enable_supernode_tracking:
                print("Supercluster Visualization:")
                for supernode in clusters.get("superclusters", []):
                    print(f"Supernode {supernode['id']} - Efficiency: {supernode['efficiency']}%")

            logging.info("Clusters visualized successfully.")
        except Exception as e:
            logging.error(f"Error visualizing clusters: {e}")

    def display_insights(self, insights):
        """
        Displays insights generated by the system.

        Args:
            insights (dict): Dictionary of insights to display.

        Returns:
            None
        """
        try:
            print("Insights Visualization:")
            print("Validated Insights:")
            for insight in insights.get("validated_insights", []):
                print(f"  - {insight}")

            print("Speculative Perspectives:")
            for perspective in insights.get("speculative_perspectives", []):
                print(f"  - {perspective}")

            if self.data_progression_logging:
                print("Data Progression:")
                clarity = insights.get("clarity", {})
                print(f"  Validated Count: {clarity.get('validated_count', 0)}")
                print(f"  Speculative Count: {clarity.get('speculative_count', 0)}")

            logging.info("Insights visualized successfully.")
        except Exception as e:
            logging.error(f"Error displaying insights: {e}")

    def plot_ic50_distribution(self, ic50_values):
        """
        Plots the distribution of IC50 values using a histogram.

        Args:
            ic50_values (list): List of IC50 values.
        """
        try:
            plt.figure(figsize=(8, 6))
            plt.hist(ic50_values, bins=20, color='skyblue', edgecolor='black')
            plt.title('Distribution of IC50 Values')
            plt.xlabel('IC50 (nM)')
            plt.ylabel('Frequency')
            plt.yscale('log')  # Use a logarithmic scale for y-axis due to wide range of IC50 values
            plt.grid(True)
            plt.show()
            logging.info("IC50 distribution plot generated.")

        except Exception as e:
            logging.error(f"Error plotting IC50 distribution: {e}")

    def plot_mw_vs_logp(self, mw_values, logp_values):
        """
        Plots molecular weight (MW) vs. LogP.

        Args:
            mw_values (list): List of molecular weight values.
            logp_values (list): List of LogP values.
        """
        try:
            plt.figure(figsize=(8, 6))
            plt.scatter(mw_values, logp_values, alpha=0.7, color='blue')
            plt.title('Molecular Weight vs. LogP')
            plt.xlabel('Molecular Weight')
            plt.ylabel('LogP')
            plt.grid(True)
            plt.show()
            logging.info("MW vs. LogP plot generated.")

        except Exception as e:
            logging.error(f"Error plotting MW vs. LogP: {e}")

    def plot_clustering(self, data, labels, title="Cluster Visualization"):
        """
        Plots the results of clustering using a scatter plot.

        Args:
            data (list): List of numerical data points.
            labels (list): List of cluster labels for each data point.
            title (str): Title of the plot.
        """
        try:
            plt.figure(figsize=(8, 6))
            plt.scatter(range(len(data)), data, c=labels, cmap='viridis', alpha=0.7)
            plt.title(title)
            plt.xlabel('Data Point Index')
            plt.ylabel('Data Value')
            plt.grid(True)
            plt.show()
            logging.info(f"{title} plot generated.")

        except Exception as e:
            logging.error(f"Error plotting clustering: {e}")
